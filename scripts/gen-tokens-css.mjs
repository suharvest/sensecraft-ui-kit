/**
 * 由 src/theme/tokens.ts 生成 dist/tokens.css —— Vue / 原生 JS 应用引用同一份数值。
 * 通过 vite build 产出的 ESM 入口读取，保证与 antd theme 同源。
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const distEntry = pathToFileURL(resolve(root, 'dist/index.js')).href;

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const mod = await import(distEntry);
const { colors, statusColors, borderRadius, zIndex, layoutSizes, fontFamilySans, modalWidth } = mod;

const lines = [
  '/* Generated by scripts/gen-tokens-css.mjs — do not edit by hand. */',
  '/* Source of truth: src/theme/tokens.ts */',
  ':root {',
];

for (const [k, v] of Object.entries(colors)) lines.push(`  --sc-color-${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(statusColors)) {
  lines.push(`  --sc-status-${k}-bg: ${v.bg};`);
  lines.push(`  --sc-status-${k}-fg: ${v.fg};`);
}
for (const [k, v] of Object.entries(borderRadius)) {
  lines.push(`  --sc-radius-${k === 'DEFAULT' ? 'base' : kebab(k)}: ${v};`);
}
for (const [k, v] of Object.entries(zIndex)) lines.push(`  --sc-z-${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(layoutSizes)) lines.push(`  --sc-layout-${kebab(k)}: ${v}px;`);
for (const [k, v] of Object.entries(modalWidth)) lines.push(`  --sc-modal-width-${kebab(k)}: ${v}px;`);
lines.push(`  --sc-font-sans: ${fontFamilySans.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};`);
lines.push('}');
lines.push('');

const statusClasses = Object.keys(statusColors)
  .map(
    (k) =>
      `.sc-status-badge.sc-status-${k} { background: var(--sc-status-${k}-bg); color: var(--sc-status-${k}-fg); }`,
  )
  .join('\n');

lines.push(
  '.sc-status-badge {',
  '  display: inline-flex;',
  '  align-items: center;',
  '  padding: 2px 8px;',
  '  border-radius: var(--sc-radius-base);',
  '  font-size: 12px;',
  '  line-height: 20px;',
  '}',
  statusClasses,
  '',
);

mkdirSync(resolve(root, 'dist'), { recursive: true });
writeFileSync(resolve(root, 'dist/tokens.css'), lines.join('\n'), 'utf8');
console.log('wrote dist/tokens.css');
